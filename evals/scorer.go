package evals

import (
	"context"
	"strings"
	"time"
	"unicode"
)

func SplitClaims(answer string) []string {
	var claims []string
	start := 0
	runes := []rune(answer)
	flush := func(end int) {
		c := strings.TrimSpace(string(runes[start:end]))
		if len([]rune(c)) >= 10 {
			claims = append(claims, c)
		}
	}
	for i, r := range runes {
		if r == '.' || r == '!' || r == '?' {
			next := i + 1
			if next >= len(runes) || unicode.IsSpace(runes[next]) {
				flush(i + 1)
				start = next
			}
		}
	}
	flush(len(runes))
	return claims
}

func PrecisionRecall(retrieved []string, relevant []string, k int) (precision, recall float64) {
	if k <= 0 || len(relevant) == 0 {
		return 0, 0
	}
	if len(retrieved) > k {
		retrieved = retrieved[:k]
	}
	rel := map[string]bool{}
	for _, d := range relevant {
		rel[d] = true
	}
	// precision: share of retrieved chunks that come from a relevant doc (two chunks of
	// the same doc both count — they are both useful context). recall: share of relevant
	// docs found at least once — a doc retrieved twice is still one doc, so recall never
	// exceeds 1.
	hits := 0
	found := map[string]bool{}
	for _, d := range retrieved {
		if rel[d] {
			hits++
			found[d] = true
		}
	}
	return float64(hits) / float64(len(retrieved)), float64(len(found)) / float64(len(relevant))
}

type ClaimResult struct {
	Claim         string `json:"claim"`
	Supported     bool   `json:"supported"`
	Justification string `json:"justification"`
}

type PairResult struct {
	Question      string        `json:"question"`
	Faithfulness  float64       `json:"faithfulness"`
	Claims        []ClaimResult `json:"claims"`
	Precision     float64       `json:"precision_at_k"`
	Recall        float64       `json:"recall_at_k"`
	Retrieved     []string      `json:"retrieved"`
	RetrievalMiss bool          `json:"retrieval_miss"`
	// LatencyS and Tokens describe the answer under test only: generation
	// seconds and completion tokens for Track L runs, zero for runs that
	// score the frozen golden answers (no generation happened).
	LatencyS float64 `json:"latency_s"`
	Tokens   int     `json:"tokens"`
}

type Searcher func(ctx context.Context, query string, topK int) ([]Chunk, error)

// Answerer generates the answer under test from the question and the
// retrieved context. It returns the answer and its completion-token count
// (Track L: the model under test; the judge stays fixed).
type Answerer func(ctx context.Context, question, contextText string) (answer string, completionTokens int, err error)

func ScorePair(ctx context.Context, p Pair, search Searcher, judge Judge, topK int) (PairResult, error) {
	chunks, err := search(ctx, p.Question, topK)
	if err != nil {
		return PairResult{}, err
	}
	retrieved, ctxParts := splitRetrieved(chunks)
	precision, recall := PrecisionRecall(retrieved, p.DocIDs, topK)
	if recall == 0 {
		// Retrieval missed every relevant doc: the judge would score a true
		// answer against the wrong context, so judging here would lie.
		// Report the miss and skip the judge entirely (no claims judged).
		return PairResult{
			Question:      p.Question,
			Retrieved:     retrieved,
			Precision:     precision,
			Recall:        recall,
			RetrievalMiss: true,
		}, nil
	}
	return judgeAnswer(ctx, p.Question, p.Answer, retrieved, strings.Join(ctxParts, "\n---\n"), precision, recall, judge)
}

// ScoreGeneratedPair is ScorePair with the answer generated by the model under
// test instead of read from the golden file: same retrieval, same miss rule,
// same judge. A generation failure fails the pair loudly — an unanswered
// model is not a zero, and scoreOnce writes nothing on failure either way.
func ScoreGeneratedPair(ctx context.Context, p Pair, search Searcher, judge Judge, answer Answerer, topK int) (PairResult, error) {
	chunks, err := search(ctx, p.Question, topK)
	if err != nil {
		return PairResult{}, err
	}
	retrieved, ctxParts := splitRetrieved(chunks)
	precision, recall := PrecisionRecall(retrieved, p.DocIDs, topK)
	if recall == 0 {
		return PairResult{
			Question:      p.Question,
			Retrieved:     retrieved,
			Precision:     precision,
			Recall:        recall,
			RetrievalMiss: true,
		}, nil
	}
	contextText := strings.Join(ctxParts, "\n---\n")
	start := time.Now()
	text, tokens, err := answer(ctx, p.Question, contextText)
	if err != nil {
		return PairResult{}, err
	}
	res, err := judgeAnswer(ctx, p.Question, text, retrieved, contextText, precision, recall, judge)
	if err != nil {
		return res, err
	}
	res.LatencyS = time.Since(start).Seconds()
	res.Tokens = tokens
	return res, nil
}

func splitRetrieved(chunks []Chunk) (retrieved, ctxParts []string) {
	for _, c := range chunks {
		ctxParts = append(ctxParts, c.Text)
		retrieved = append(retrieved, c.DocID)
	}
	return retrieved, ctxParts
}

func judgeAnswer(ctx context.Context, question, answer string, retrieved []string, contextText string, precision, recall float64, judge Judge) (PairResult, error) {
	claims := SplitClaims(answer)
	res := PairResult{Question: question, Retrieved: retrieved, Precision: precision, Recall: recall}
	supported := 0
	for _, cl := range claims {
		ok, just, err := judge.JudgeClaim(ctx, cl, contextText)
		if err != nil {
			return res, err
		}
		res.Claims = append(res.Claims, ClaimResult{Claim: cl, Supported: ok, Justification: just})
		if ok {
			supported++
		}
	}
	if len(claims) > 0 {
		res.Faithfulness = float64(supported) / float64(len(claims))
	}
	return res, nil
}
